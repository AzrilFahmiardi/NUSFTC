// Quick lookup function
export function getIngredientById(id: string): MoBaiIngredient | undefined {
  return MOBai_INGREDIENTS.find(i => i.id === id);
}

// Search by category
export function getIngredientsByCategory(category: MoBaiIngredient['category']): MoBaiIngredient[] {
  return MOBai_INGREDIENTS.filter(i => i.category === category);
}

// Get allergens list
export function getAllAllergens(): string[] {
  const allergenSet = new Set<string>();
  MOBai_INGREDIENTS.forEach(i => {
    i.allergens.forEach(a => allergenSet.add(a));
  });
  return Array.from(allergenSet).sort();
}

